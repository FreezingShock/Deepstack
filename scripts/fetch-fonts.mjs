// One-off: downloads the latin subsets of the Google fonts the game uses into public/fonts/google/ and writes src/ui/googleFonts.css.
// Run `node scripts/fetch-fonts.mjs` only when the font list changes; the outputs are committed so the game makes no third-party request.
import {mkdirSync, writeFileSync} from 'node:fs';
const Q = 'family=Fuzzy+Bubbles:wght@400;700&family=IM+Fell+English:ital@0;1&family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;1,6..72,400&family=Source+Sans+3:wght@400;500;600;700&family=Cinzel:wght@500;600;700&family=Special+Elite';
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const css = await (await fetch(`https://fonts.googleapis.com/css2?${Q}&display=swap`, {headers: {'User-Agent': UA}})).text();
mkdirSync('public/fonts/google', {recursive: true});
const files = new Map(), faces = new Map(); // faces: variable files serve several weights, merged into one range
let out = '/* Generated by scripts/fetch-fonts.mjs. Latin subsets of the Google fonts, self-hosted from public/fonts/google/. */\n';
for (const m of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
  if (m[1] !== 'latin') continue;
  const body = m[2], url = body.match(/url\((https:[^)]+)\)/)[1];
  const fam = body.match(/font-family: '([^']+)'/)[1], style = body.match(/font-style: (\w+)/)[1], weight = body.match(/font-weight: ([\d ]+)/)[1].trim();
  const range = body.match(/unicode-range: ([^;]+)/)?.[1];
  if (!files.has(url)) {
    const name = `${fam.replace(/\s+/g, '')}-${style}-${weight.replace(' ', '_')}.woff2`;
    writeFileSync(`public/fonts/google/${name}`, Buffer.from(await (await fetch(url)).arrayBuffer()));
    files.set(url, name);
  }
  const f = faces.get(url) || {fam, style, range, ws: []}; f.ws.push(+weight.split(' ')[0]); faces.set(url, f);
}
for (const [url, f] of faces) {
  const lo = Math.min(...f.ws), hi = Math.max(...f.ws);
  out += `@font-face{font-family:'${f.fam}';font-style:${f.style};font-weight:${lo === hi ? lo : lo + ' ' + hi};font-display:swap;src:url('/fonts/google/${files.get(url)}') format('woff2')${f.range ? `;unicode-range:${f.range}` : ''}}\n`;
}
writeFileSync('src/ui/googleFonts.css', out);
console.log([...files.values()].join('\n'));
