// Regenerates the auto section of docs/feature-inventory.md (file map: path, lines, purpose, tests that import it).
// Usage: node scripts/inventory.mjs [--out <file>]   (no CI, no dependencies; hand-written sections are kept)
import {readFileSync, writeFileSync, readdirSync, statSync, existsSync} from 'node:fs';
import {join, relative} from 'node:path';

const root = process.cwd();
const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : join(root, 'docs/feature-inventory.md');
const BEGIN = '<!-- inventory:begin -->', END = '<!-- inventory:end -->';

const walk = d => readdirSync(d).flatMap(n => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const rel = p => relative(root, p).split('\\').join('/');
const files = walk(join(root, 'src')).filter(f => /\.(js|css)$/.test(f)).map(rel).sort();
const tests = existsSync(join(root, 'test')) ? readdirSync(join(root, 'test')).filter(f => f.endsWith('.test.js')) : [];
const testSrc = Object.fromEntries(tests.map(t => [t, readFileSync(join(root, 'test', t), 'utf8')]));

function purpose(src) {
  const m = src.match(/^\s*(?:\/\*+\s*([^\n*]*)|\/\/\s*(.*))/);
  return ((m && (m[1] || m[2])) || '').replace(/\*\/.*$/, '').trim().replace(/\|/g, '/').slice(0, 90);
}

const rows = files.map(f => {
  const src = readFileSync(join(root, f), 'utf8');
  const base = f.split('/').pop().replace(/\.(js|css)$/, '');
  const used = tests.filter(t => testSrc[t].includes('/' + base + '.') || testSrc[t].includes('/' + base + "'")).map(t => t.replace('.test.js', ''));
  return `| \`${f}\` | ${src.split('\n').length} | ${purpose(src)} | ${used.join(', ') || (f.endsWith('.css') ? 'css-sanity' : '-')} |`;
});

const block = [BEGIN, `_Generated by \`node scripts/inventory.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`, '',
  '| File | Lines | Purpose (first comment) | Tests |', '|---|---|---|---|', ...rows, END].join('\n');

let doc = existsSync(out) ? readFileSync(out, 'utf8') : `# Feature inventory\n\n${BEGIN}\n${END}\n`;
doc = doc.includes(BEGIN) ? doc.replace(new RegExp(BEGIN + '[\\s\\S]*?' + END), () => block) : doc + '\n' + block + '\n';
writeFileSync(out, doc);
console.log(`inventory: ${files.length} files -> ${rel(out)}`);
