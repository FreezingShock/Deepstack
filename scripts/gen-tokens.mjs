// Writes src/theme/tokens.css from src/theme/colors.js. Run: npm run gen:tokens
import {writeFileSync} from 'node:fs';
import {tokenEntries} from '../src/theme/colors.js';
export function tokensCss(){
 return '/* GENERATED by scripts/gen-tokens.mjs from src/theme/colors.js. Edit colors.js, then run `npm run gen:tokens`. */\n:root{\n'+tokenEntries().map(([k,v])=>`  ${k}:${v};`).join('\n')+'\n}\n';
}
if(import.meta.url===`file://${process.argv[1]}`)writeFileSync('src/theme/tokens.css',tokensCss());
