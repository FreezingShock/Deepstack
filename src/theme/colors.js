const kebab=s=>s.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
// Every token as [cssVarName, value]. Order is the order written to tokens.css.
export function tokenEntries(){
 const out=[];
 for(const[k,v]of Object.entries(COLORS))out.push([`--c-${k}`,v]);
 for(const[k,v]of Object.entries(ALPHA))out.push([`--c-${k}`,v]);
 for(const[t,c]of Object.entries(TIER_COLORS)){out.push([`--tier-${t}`,c.spine]);out.push([`--tier-${t}-ink`,c.ink]);}
 for(const[f,c]of Object.entries(FLOOR_COLORS))for(const[k,v]of Object.entries(c))out.push([`--floor-${f}-${kebab(k)}`,v]);
 return out;
}
